export function t(lang, key, params) {
  const table = STRINGS[lang] || STRINGS.en
  let text = table[key] ?? STRINGS.en[key] ?? key
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}
