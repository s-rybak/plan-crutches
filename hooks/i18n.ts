export type StringKey = keyof (typeof STRINGS)['en']

export function t(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  const table: Record<StringKey, string> = STRINGS[lang]
  let text: string = table[key]
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

export function statusLabel(lang: Lang, status: FileStatus | 'mixed' | 'unchanged'): string {
  const key = `status_${status}` as StringKey
  return t(lang, key)
}

export const otherLang = (lang: Lang): Lang => (lang === 'en' ? 'uk' : 'en')
